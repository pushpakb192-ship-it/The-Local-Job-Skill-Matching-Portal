def init_db():
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    # Base jobs table
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS jobs (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        title TEXT NOT NULL,
        company TEXT NOT NULL,
        category TEXT NOT NULL,
        location TEXT NOT NULL,
        neighborhood TEXT NOT NULL,
        distance_km REAL NOT NULL,
        job_type TEXT NOT NULL,
        pay TEXT NOT NULL,
        pay_period TEXT NOT NULL,
        experience_level TEXT NOT NULL,
        urgent INTEGER DEFAULT 0,
        verified_employer INTEGER DEFAULT 0,
        contact_email TEXT NOT NULL,
        description TEXT NOT NULL,
        required_skills TEXT NOT NULL,
        nice_to_have_skills TEXT NOT NULL,
        benefits TEXT NOT NULL,
        posted_date TEXT NOT NULL
    )
    """)

    # Base applications table
    cursor.execute("""
    CREATE TABLE IF NOT EXISTS applications (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        job_id INTEGER NOT NULL,
        applicant_name TEXT NOT NULL,
        applicant_email TEXT NOT NULL,
        applicant_phone TEXT,
        applicant_skills TEXT,
        message TEXT,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (job_id) REFERENCES jobs(id)
    )
    """)

    # Safe Schema Migrations for jobs table
    cursor.execute("PRAGMA table_info(jobs)")
    existing_cols = {row[1]: row for row in cursor.fetchall()}

    columns_to_add = [
        ("latitude", "REAL"),
        ("longitude", "REAL"),
        ("salary_min", "REAL"),
        ("salary_max", "REAL"),
        ("currency", "TEXT DEFAULT 'INR'"),
        ("is_negotiable", "INTEGER DEFAULT 0"),
        ("salary_disclosed", "INTEGER DEFAULT 1"),
        ("employment_type", "TEXT DEFAULT 'Full-time'"),
        ("pin_code", "TEXT"),
        ("city", "TEXT"),
        ("state", "TEXT"),
        ("status", "TEXT DEFAULT 'published'"),
        ("expires_at", "TEXT"),
        ("deadline", "TEXT"),
        ("job_source", "TEXT DEFAULT 'demo'"),
        ("verification_status", "TEXT DEFAULT 'demo'"),
        ("application_url", "TEXT")
    ]

    for col_name, col_type in columns_to_add:
        if col_name not in existing_cols:
            cursor.execute(f"ALTER TABLE jobs ADD COLUMN {col_name} {col_type}")

    # Safe Schema Migrations for applications table
    cursor.execute("PRAGMA table_info(applications)")
    app_cols = {row[1]: row for row in cursor.fetchall()}
    app_columns_to_add = [
        ("applicant_education", "TEXT"),
        ("applicant_experience", "TEXT")
    ]
    for col_name, col_type in app_columns_to_add:
        if col_name not in app_cols:
            cursor.execute(f"ALTER TABLE applications ADD COLUMN {col_name} {col_type}")

    conn.commit()

